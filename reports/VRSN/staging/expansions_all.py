def insert_before(text, marker, content):
    """Insert content before a marker string"""
    idx = text.find(marker)
    if idx == -1:
        print(f"  WARNING: marker not found: {marker[:60]}...")
        return text
    # Find the --- separator before the marker
    sep = text.rfind('---', max(0, idx-200), idx)
    if sep != -1 and idx - sep < 200:
        insert_pos = sep
        return text[:insert_pos] + content + '\n\n' + text[insert_pos:]
    else:
        return text[:idx] + content + '\n\n' + text[idx:]

def insert_after_section(text, section_start, content):
    """Insert content after a section (before the next ## heading)"""
    idx = text.find(section_start)
    if idx == -1:
        print(f"  WARNING: section not found: {section_start[:60]}...")
        return text
    # Find the next ## heading after this section
    next_heading = re.search(r'\n## ', text[idx + len(section_start):])
    if next_heading:
        insert_pos = idx + len(section_start) + next_heading.start()
        # Find preceding ---
        sep = text.rfind('---', max(0, insert_pos-200), insert_pos)
        if sep != -1 and insert_pos - sep < 200:
            insert_pos = sep
        return text[:insert_pos] + '\n\n' + content + '\n\n' + text[insert_pos:]
    else:
        return text + '\n\n' + content

